function renderWakaf() {
  const stats = document.querySelector("[data-wakaf-stats]");
  const locations = document.querySelector("[data-wakaf-locations]");

  if (stats) {
    stats.innerHTML = wakafData.stats.map(([value, key]) => `
      <article class="stat-card">
        <strong>${value}</strong>
        <span data-i18n="wakaf.${key}"></span>
      </article>
    `).join("");
  }

  if (locations) {
    locations.innerHTML = wakafData.locations
      .map((location) => `<div class="location-card">${location}</div>`)
      .join("");
  }
}

document.addEventListener("DOMContentLoaded", () => {
  renderWakaf();

  const language = localStorage.getItem("emyDahliaLanguage") || "ms";
  applyLanguage(language);

  document.querySelectorAll(".language-option").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.language));
  });

  const menuToggle = document.querySelector(".menu-toggle");
  const nav = document.getElementById("pageNav");
  if (menuToggle && nav) {
    menuToggle.addEventListener("click", () => {
      const open = menuToggle.getAttribute("aria-expanded") === "true";
      menuToggle.setAttribute("aria-expanded", String(!open));
      nav.classList.toggle("is-open", !open);
    });
    nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
      nav.classList.remove("is-open");
      menuToggle.setAttribute("aria-expanded", "false");
    }));
  }
});
